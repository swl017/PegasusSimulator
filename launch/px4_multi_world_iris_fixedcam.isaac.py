    def vehicle_factory(self, vehicle_id: int, gap_x_axis: float):
        """Auxiliar method to create multiple multirotor vehicles

        Args:
            vehicle_id (_type_): _description_
        """

        # Create the vehicle
        # Try to spawn the selected robot in the world to the specified namespace
        config_multirotor = MultirotorConfig()
        # RAL ticket 019 revisit2 W0f: does this vehicle carry a camera at all?
        _has_camera = vehicle_id in self._camera_ids
        # MAS ticket 055 D2: and if so, is it the interceptor's fixed fisheye?
        _fixed_camera = vehicle_id in self._fixed_camera_ids

        # Create the multirotor configuration
        mavlink_config = PX4MavlinkBackendConfig({
            "vehicle_id": vehicle_id,
            "px4_autolaunch": True,
            "px4_dir": self.pg.px4_path,
            "px4_vehicle_model": self.pg.px4_default_airframe # CHANGE this line to 'iris' if using PX4 version bellow v1.14
        })
        config_multirotor.backends = [
            PX4MavlinkBackend(mavlink_config),
            ROS2Backend(vehicle_id=vehicle_id,
                        config={
                            "namespace": self.namespace,
                            "pub_sensors": True,
                            "pub_graphical_sensors": _has_camera,
                            "pub_state": True,
                            "sub_control": False,
                            # MAS ticket 055: the interceptor has no zoom hardware, and
                            # MonocularCamera.set_zoom would rebuild the focal length from
                            # mean(fx, fy) using a hardcoded 3 um pixel size — overwriting
                            # the aperture that carries fx. `fixed_mount_publisher` does not
                            # publish camera/zoom_level_cmd, so nothing should arrive; this
                            # closes the door rather than trusting that.
                            "sub_zoom": not _fixed_camera,
                        })]

        # RAL ticket 019 revisit2 W0f: skip the render product entirely for vehicles that have
        # no camera consumer (see CAMERA_VEHICLES above). An empty graphical_sensors list is
        # safe by construction — the post-world.reset() property loop iterates
        # `vehicle._graphical_sensors` and simply does nothing — and the USD prim is untouched.
        if _has_camera and _fixed_camera:
            # MAS ticket 055. The 3x3 `intrinsics` here only seeds MonocularCamera.set_zoom
            # (which this vehicle has disabled) — the real lens is authored on the prim
            # after world.reset() by author_fisheye_camera(). It is still given the correct
            # ISOTROPIC matrix so that, if zoom is ever re-enabled by mistake, set_zoom's
            # mean(fx, fy) reconstruction is a no-op rather than a silent 444.76 -> 388.87
            # miscalibration.
            config_multirotor.graphical_sensors = [
                MonocularCamera("/pitch_link/camera",
                config={
                    "frequency": 25,
                    "resolution": (self._fixed_cam_width, self._fixed_cam_height),
                    "position": np.array([0, 0, 0]),
                    "orientation": np.array([0.0, 0.0, 0.0]),
                    "intrinsics": np.array([[self._fixed_fx, 0, self._fixed_cx],
                                            [0, self._fixed_fx, self._fixed_cy],
                                            [0, 0, 1]]),
                    }
                )
            ]
        elif _has_camera:
            config_multirotor.graphical_sensors = [
                MonocularCamera("/pitch_link/camera",
                config={
                    "frequency": 25,
                    "resolution": (self._cam_width, self._cam_height),
                    "position": np.array([0, 0, 0]),
                    "orientation": np.array([0.0, 0.0, 0.0]),
                    "intrinsics": np.array(self._cam_matrix),
                    }
                )
            ]
        else:
            config_multirotor.graphical_sensors = []
            print(f"[PegasusApp] vehicle {vehicle_id}: camera SKIPPED (not in CAMERA_VEHICLES)")

        vehicle_name = self.namespace + str(vehicle_id)
        vehicle_stage_path = "/World/" + vehicle_name
        # vehicle_stage_path = "/World/quadrotor"


        vehicle = Multirotor(
            vehicle_stage_path,
            # ROBOTS['Iris'],
            ROBOTS['IrisGimbal3'],
            vehicle_id,
            [self.world_offset_x + gap_x_axis * (vehicle_id+1), self.world_offset_y + gap_x_axis * (vehicle_id+1), self.world_offset_z + 2.0],
            Rotation.from_euler("XYZ", [0.0, 0.0, 3.14], degrees=True).as_quat(),
            config=config_multirotor)
        self.vehicles += [vehicle]
        # MAS ticket 055: the post-reset camera loop has to know which vehicle a sensor
        # belongs to in order to pick fisheye vs pinhole, and Vehicle exposes only
        # `_vehicle_name` / `_stage_prefix`, not the id it was constructed with.
        self._vehicle_by_id[vehicle_id] = vehicle
        asyncio.ensure_future(self.create_ros_action_graph(vehicle_stage_path, vehicle_name))
        # asyncio.ensure_future(self.create_ros_camera_graph(vehicle_stage_path, vehicle_name))

