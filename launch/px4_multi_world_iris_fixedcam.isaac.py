        # reaches ros2_backend — `add_monocular_camera_writter` calls read_camera_info() once
        # and freezes k/p into the CameraInfo writer, so a property set afterwards changes the
        # render without changing what is published. The 100-tick suppression at the top of
        # MonocularCamera.update gives the margin; timeline.play() has not been called yet.
        f_stop = 1.8
