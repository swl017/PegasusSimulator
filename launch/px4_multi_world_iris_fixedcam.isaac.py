    def author_fisheye_camera(self, camera, vehicle_id: int, f_stop: float,
                              focus_distance: float):
        """Author the interceptor's fisheye lens onto one camera prim (MAS ticket 055).

        Deliberately does NOT use `Camera.set_kannala_brandt_properties`, which exists for
        exactly this distortion model. That helper fits the fTheta polynomial from sample
        points generated by `point_to_theta` (camera.py:53) — ideal-pinhole pixels — so for a
        157 deg lens it never samples past 58.97 deg while the image reaches 92 deg, leaving
        the outer third of the image radius as degree-4 extrapolation worth up to 3.5 deg of
        rendered bearing error. The coefficients here were fitted over the true angular range
        instead (probe_fisheye_ftheta.py §Q3/§Q5) and go in through the same lower-level call
        the helper itself ends at.

        Fail-closed, like `disable_vehicle_vehicle_collision`: every authored attribute is
        read back. A lens that silently failed to apply would produce a session that looks
        right, flies for an hour and yields bearings from the wrong camera — which is the
        whole failure class this ticket exists to prevent.
        """
        from pxr import Sdf

        # 1. Projection type FIRST — every set_fisheye_* call raises without it
        #    (camera.py:1251, :1291, :1400). Verified immediately rather than at the readback
        #    below, because if it did not take, step 3 throws Isaac's own bare
        #    Exception("fisheye projection type is not set") first — which names neither the
        #    vehicle nor where to look.
        camera.set_projection_type("fisheyePolynomial")
        _got_type = camera.get_projection_type()
        if "fisheye" not in (_got_type or ""):
            raise RuntimeError(
                "px4_%d: cameraProjectionType is %r after asking for 'fisheyePolynomial' — "
                "the prim rejected the projection type, so no fisheye property can be "
                "authored at all. Refusing to boot [MAS ticket 055]."
                % (vehicle_id, _got_type))

        # 2. The pinhole-side properties. These do NOT drive the fTheta render, but
        #    read_camera_info builds the published K from focalLength/horizontalAperture
        #    (camera_info_utils.py:93-94), so this is what puts fx on the wire.
        #    HORIZONTAL ONLY — set_vertical_aperture would rewrite horizontalAperture
        #    behind us (camera.py:1149-1153).
        camera.set_focal_length(self._cam_focal_length / 10.0)          # mm → cm
        camera.set_focus_distance(focus_distance)
        camera.set_lens_aperture(f_stop * 100.0)
        camera.set_horizontal_aperture(self._fixed_h_aperture / 10.0)   # mm → cm
        camera.set_clipping_range(0.1, 1.0e5)

        # 3. The render law itself.
        camera.set_fisheye_polynomial_properties(
            nominal_width=self._fixed_cam_width,
            nominal_height=self._fixed_cam_height,
            optical_centre_x=self._fixed_cx,
            optical_centre_y=self._fixed_cy,
            max_fov=self._fixed_ftheta_max_fov,
            polynomial=self._fixed_ftheta_poly)

        # 4. What the ROS consumer routes on. Passed verbatim into
        #    CameraInfo.distortion_model / .d by the bridge, so it must be the string
        #    mas_bearing_loc knows ("equidistant"), not Isaac's own "kannalaBrandt".
        camera.prim.CreateAttribute(
            "physicalDistortionModel", Sdf.ValueTypeNames.String).Set(
                self._fixed_distortion_model)
        camera.prim.CreateAttribute(
            "physicalDistortionCoefficients", Sdf.ValueTypeNames.FloatArray, False).Set(
                self._fixed_d)

        # 5. Read back. set_fisheye_polynomial_properties skips any coefficient that is
        #    falsy (`if polynomial[i]:`, camera.py:1267), so a coefficient that failed to
        #    author is a real possibility rather than a paranoid one.
        got_type = camera.get_projection_type()
        (n_w, n_h, o_cx, o_cy, max_fov, poly) = camera.get_fisheye_polynomial_properties()
        got_model = camera.prim.GetAttribute("physicalDistortionModel").Get()
        got_d = list(camera.prim.GetAttribute("physicalDistortionCoefficients").Get() or [])
        fx_published = (self._fixed_cam_width * camera.get_focal_length()
                        / camera.get_horizontal_aperture())

        problems = []
        if "fisheye" not in (got_type or ""):
            problems.append(f"projection type is {got_type!r}")
        if (n_w, n_h) != (self._fixed_cam_width, self._fixed_cam_height):
            problems.append(f"ftheta frame is {n_w}x{n_h}")
        if abs((o_cx or 0) - self._fixed_cx) > 1e-3 or abs((o_cy or 0) - self._fixed_cy) > 1e-3:
            problems.append(f"ftheta centre is ({o_cx}, {o_cy})")
        if max_fov is None or abs(max_fov - self._fixed_ftheta_max_fov) > 1e-2:
            problems.append(f"ftheta max_fov is {max_fov}")
        for i, want in enumerate(self._fixed_ftheta_poly):
            got = poly[i]
            if got is None or abs(got - want) > max(1e-12, abs(want) * 1e-5):
                problems.append(f"fthetaPoly{chr(ord('A') + i)} is {got!r}, wanted {want!r}")
        if got_model != self._fixed_distortion_model:
            problems.append(f"physicalDistortionModel is {got_model!r}")
        if len(got_d) != 4 or any(abs(a - b) > 1e-6 for a, b in zip(got_d, self._fixed_d)):
            problems.append(f"physicalDistortionCoefficients are {got_d}")
        if abs(fx_published - self._fixed_fx) > 0.1:
            problems.append(f"published fx would be {fx_published:.4f}, "
                            f"wanted {self._fixed_fx:.4f}")
        if problems:
            raise RuntimeError(
                "fisheye authoring readback FAILED on px4_%d: %s — refusing to boot a session "
                "whose camera is not the one it claims to be [MAS ticket 055]"
                % (vehicle_id, "; ".join(problems)))

        print("[PegasusApp] px4_%d FIXED FISHEYE: %dx%d, fx=%.4f px (published), "
              "cx/cy=%.1f/%.1f, maxFov=%.2f deg, model=%s — readback verified "
              "[MAS ticket 055]"
              % (vehicle_id, self._fixed_cam_width, self._fixed_cam_height, fx_published,
                 o_cx, o_cy, max_fov, got_model))

    def disable_vehicle_vehicle_collision(self, num_vehicles: int):
        """Author a SELF-FILTERING UsdPhysics.CollisionGroup over the vehicle prims.

        A collision group that lists ITSELF in `filteredGroups` means its members do not
        collide with one another, while collisions with everything OUTSIDE the group —
        notably the ground plane — are untouched. That is exactly the semantics RAL
        ticket 055 S21 needs: an interceptor may fly through the target to its true CPA,
        but a vehicle that falls still lands.

        Fail-closed by construction. A filter that silently fails to author is worse than
        no filter at all, because the cohort would look protected, run for 40 minutes and
        then lose a vehicle anyway — which is the failure this exists to prevent. So the
        prims are checked before authoring and the authored targets are read back after.

        Returns the READBACK-VERIFIED group description (path, filteredGroups, members) so
        the boot label reports what was authored rather than what was requested.
        """
        import omni.usd
        from pxr import Usd, UsdPhysics

        stage = omni.usd.get_context().get_stage()
        group_path = "/World/CollisionGroups/vehicles"
        group = UsdPhysics.CollisionGroup.Define(stage, group_path)

        # Self-filtering: members of this group ignore each other.
        filtered = group.CreateFilteredGroupsRel()
        filtered.AddTarget(group_path)

        # Membership. Newer USD exposes the collection through the schema; fall back to
        # the raw Usd.CollectionAPI instance name ("colliders") on older builds.
        try:
            includes = group.GetCollidersCollectionAPI().CreateIncludesRel()
        except Exception:
            includes = Usd.CollectionAPI.Apply(
                group.GetPrim(), "colliders").CreateIncludesRel()

        members = []
        for i in range(1, num_vehicles + 1):
            prim_path = "/World/" + self.namespace + str(i)
            if not stage.GetPrimAtPath(prim_path).IsValid():
                raise RuntimeError(
                    "DISABLE_VEHICLE_COLLISION: vehicle prim %s is missing — refusing to "
                    "boot with a filter that would silently not apply" % prim_path)
            includes.AddTarget(prim_path)
            members.append(prim_path)

        authored_filter = [t.pathString for t in filtered.GetTargets()]
        authored_members = [t.pathString for t in includes.GetTargets()]
        if group_path not in authored_filter or sorted(authored_members) != sorted(members):
            raise RuntimeError(
                "DISABLE_VEHICLE_COLLISION: readback mismatch — filteredGroups=%s "
                "includes=%s (expected self-filter on %s over %s)"
                % (authored_filter, authored_members, group_path, members))

        print("[PegasusApp] DISABLE_VEHICLE_COLLISION=1 -> self-filtering CollisionGroup "
              "%s over %d vehicles %s (vehicle-GROUND collision UNCHANGED) [RAL ticket 055]"
              % (group_path, len(members), members))

        return {"path": group_path,
                "filtered_groups": authored_filter,
                "members": authored_members,
                "ground_collision": "unchanged"}

    def write_boot_label(self, num_vehicles: int, nocollide_raw: str, collision_group):
        """Write the Isaac-side boot label — the machine-readable half of the boot witness.

        WHY. RAL ticket 055 `s21_deviation_deploy_assertion.md` §4: the collision regime,
        the single variable separating cohorts E58/E59 from E57/E56, is absent from the
        conductor's provenance entirely — "a reader of the provenance JSONs alone cannot
        distinguish E58 from E57" — because `experiment_conductor` has no visibility into
        THIS process's environment. Only Isaac knows the Isaac-side configuration, so
        Isaac writes it down. That ticket's filed follow-up is the conductor archiving
        this file into `boot_<id>_provenance.json`.

        It labels what was AUTHORED, not what was requested: `collision_group` is the
        readback-verified description returned by disable_vehicle_vehicle_collision(), so
        a filter that failed to apply cannot produce a label claiming it did.

        STALENESS is the hazard a well-known path invites — a consumer that reads a label
        left behind by a previous session would silently mis-label a whole cohort, which
        is the exact failure class this file exists to close. So the label carries this
        process's `pid` and `boot_unix_time`, and a consumer MUST check that `/proc/<pid>`
        is alive before trusting it (the conductor runs on this same box). The file is
        written atomically, so a reader never sees a half-written label.

        Fail-closed, like the filter above: if the label cannot be written the boot stops.
        A cohort that cannot state its own physics is the thing being prevented.
        """
        import hashlib
        import json
        import socket
        import time

        producer = os.path.abspath(__file__)
        try:
            with open(producer, "rb") as f:
                producer_sha256 = hashlib.sha256(f.read()).hexdigest()
        except OSError:
            producer_sha256 = None

        label = {
            "schema": "isaac_boot_label/1",
            # Liveness — a consumer must verify /proc/<pid> before trusting this file.
            "pid": os.getpid(),
            "boot_unix_time": time.time(),
            "hostname": socket.gethostname(),
            "producer": producer,
            "producer_sha256": producer_sha256,
            "headless": bool(args.headless),
            # The Isaac-side configuration surface that is invisible downstream.
            "num_vehicles": num_vehicles,
            "namespace": self.namespace,
            "camera_res": self._camera_res,
            "camera_width": self._cam_width,
            "camera_height": self._cam_height,
            "camera_vehicles": sorted(self._camera_ids),
            # MAS ticket 055 D2 — the fixed-fisheye selection, and the CONTRACT the ROS side
            # reads back. `gimbal_stabilizer/fixed_mount_publisher` refuses to start unless
            # its own namespace appears in `fixed_camera_vehicles`, which is what makes an
            # Isaac/ROS disagreement loud instead of silent. Consumers MUST check /proc/<pid>
            # is alive before trusting this file (see the docstring above).
            "fixed_camera_vehicles": sorted(self._fixed_camera_ids),
            "fixed_camera_vehicles_env": self._fixed_camera_env_raw,
            "fixed_camera": {
                "render_width": self._fixed_cam_width,
                "render_height": self._fixed_cam_height,
                "fx_px": self._fixed_fx,
                "cx_px": self._fixed_cx,
                "cy_px": self._fixed_cy,
                "projection_type": "fisheyePolynomial",
                "ftheta_poly_a_to_e": list(self._fixed_ftheta_poly),
                "ftheta_max_fov_deg": self._fixed_ftheta_max_fov,
                "horizontal_aperture_mm": self._fixed_h_aperture,
                "distortion_model": self._fixed_distortion_model,
                "distortion_coefficients": list(self._fixed_d),
                # The published frame is NOT what is rendered: sim_camera_relay applies the
                # 0.75 vertical squeeze. Recorded so a consumer of this label cannot mistake
                # the render frame for the frame the detector saw.
                "published_width": self._fixed_cam_width,
                "published_height": int(self._fixed_cam_height * 0.75),
                "published_fy_px": self._fixed_fx * 0.75,
                "relay_required": "sim_camera_relay/camera_relay",
            },
            "disable_vehicle_collision": collision_group is not None,
            # The raw env string as delivered ("" = unset, i.e. the default). The boolean
            # above is derived from the AUTHORED group and is the authoritative field.
            "disable_vehicle_collision_env": nocollide_raw,
            "collision_group": collision_group,
        }

        path = os.environ.get("ISAAC_BOOT_LABEL", "/tmp/isaac_boot_label.json").strip()
        tmp = path + ".%d.tmp" % os.getpid()
        try:
            with open(tmp, "w") as f:
                json.dump(label, f, indent=2, sort_keys=True)
                f.write("\n")
            os.replace(tmp, path)          # atomic: no reader sees a partial label
        except OSError as e:
            raise RuntimeError(
                "ISAAC_BOOT_LABEL: could not write the boot label to %s (%s) — refusing to "
                "boot a cohort that cannot state its own Isaac-side configuration "
                "[RAL ticket 055]" % (path, e))

        print("[PegasusApp] ISAAC_BOOT_LABEL -> %s (pid=%d, disable_vehicle_collision=%s) "
              "[RAL ticket 055]" % (path, label["pid"], label["disable_vehicle_collision"]))

    def load_flight_scene(self, usd_path: str, scale: float = 0.001, offset: tuple = (0.0, 0.0, 0.0)):
        """Load the Flight aesthetic scene USD with Y-up → Z-up rotation.

        Args:
            usd_path: Absolute path to the Flight USD file.
            scale: Uniform scale (USD is in cm with large coordinates; 0.001 fits the env).
            offset: (x, y, z) translation offset in meters after scaling.
        """
        import omni.usd
        from pxr import UsdGeom, Gf

        stage = omni.usd.get_context().get_stage()
        xform = UsdGeom.Xform.Define(stage, "/World/FlightScene")
        # Order: translate → rotate → scale (USD applies ops top-to-bottom)
        ox, oy, oz = offset
        xform.AddTranslateOp().Set(Gf.Vec3d(ox, oy, oz))
        xform.AddRotateXOp().Set(90.0)  # Y-up → Z-up
        xform.AddScaleOp().Set(Gf.Vec3f(scale, scale, scale))
        xform.GetPrim().GetReferences().AddReference(usd_path)

